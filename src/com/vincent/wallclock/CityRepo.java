    public static class City {
        public final String name;
        public final String admin;
        public final double lat;
        public final double lon;

        City(String name, String admin, double lat, double lon) {
            this.name = name;
            this.admin = admin;
            this.lat = lat;
            this.lon = lon;
        }

        public String label() {
            if (admin == null || admin.length() == 0 || admin.equals(name)) {
                return name;
            }
            return name + " · " + admin;
        }
    }

    private static List<City> cache;

    public static synchronized List<City> all() {
        if (cache == null) {
            List<City> list = new ArrayList<City>();
            String[] rows = DATA.split(";");
            for (String row : rows) {
                String[] p = row.split("\\|");
                if (p.length != 4) {
                    continue;
                }
                try {
                    list.add(new City(p[0], p[1], Double.parseDouble(p[2]), Double.parseDouble(p[3])));
                } catch (Throwable ignored) {
                }
            }
            cache = list;
        }
        return cache;
    }

    /** 按名称模糊过滤（离线） */
    public static List<City> filter(String keyword) {
        List<City> out = new ArrayList<City>();
        if (keyword == null || keyword.trim().length() == 0) {
            return out;
        }
        String k = keyword.trim();
        for (City c : all()) {
            if (c.name.contains(k) || c.admin.contains(k)) {
                out.add(c);
            }
        }
        return out;
    }

    /** 就近匹配：maxKm 内返回最近城市，否则 null */
    public static City nearest(double lat, double lon, double maxKm) {
        City best = null;
        double bestD = Double.MAX_VALUE;
        for (City c : all()) {
            double d = distanceKm(lat, lon, c.lat, c.lon);
            if (d < bestD) {
                bestD = d;
                best = c;
            }
        }
        if (best == null || bestD > maxKm) {
            return null;
        }
        return best;
    }

    public static double distanceKm(double lat1, double lon1, double lat2, double lon2) {
        double r = 6371.0;
        double dLat = Math.toRadians(lat2 - lat1);
        double dLon = Math.toRadians(lon2 - lon1);
        double a = Math.sin(dLat / 2) * Math.sin(dLat / 2)
                + Math.cos(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2))
                * Math.sin(dLon / 2) * Math.sin(dLon / 2);
        return 2 * r * Math.asin(Math.min(1.0, Math.sqrt(a)));
    }

    /** 按省/区分组，供设置页下拉使用 */
    public static Map<String, List<City>> grouped() {
        Map<String, List<City>> map = new LinkedHashMap<String, List<City>>();
        for (City c : all()) {
            List<City> l = map.get(c.admin);
            if (l == null) {
                l = new ArrayList<City>();
                map.put(c.admin, l);
            }
            l.add(c);
        }
        return map;
    }

